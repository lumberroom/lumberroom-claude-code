#!/usr/bin/env node
// Reduces tools-snapshot.json to what drift tests read (tool names, property names, required
// lists) and writes it as a TypeScript module, because the test sandbox has no fs.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const snapshot = JSON.parse(readFileSync(`${root}tools-snapshot.json`, "utf8"));
const tools = {};
for (const t of snapshot.tools) {
  const schema = t.inputSchema ?? {};
  tools[t.name] = {
    properties: Object.keys(schema.properties ?? {}).sort(),
    required: [...(schema.required ?? [])].sort(),
  };
}
const target = `${root}tests/fixtures/tools-snapshot.ts`;
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  "// Generated by scripts/snapshot-to-ts.mjs from tools-snapshot.json. Do not edit.\n" +
    `export const SNAPSHOT = ${JSON.stringify({ tools }, null, 2)} as const\n`,
);
console.log(`wrote ${Object.keys(tools).length} tools`);
